var testBuild = buildConfig{Receiver: "larek-webhook", ExternalURL: "https://grafana.k.larek.tech/"}

func build(t *testing.T, name string) Message {
	t.Helper()
	s, ok := findScenario(name)
	if !ok {
		t.Fatalf("scenario %q not found", name)
	}
	return buildMessage(testBuild, s.build(), time.Date(2026, 10, 24, 10, 18, 0, 0, time.UTC))
}

func TestFiringAndResolvedShareFingerprint(t *testing.T) {
	f := build(t, "firing").Alerts[0]
	r := build(t, "resolved").Alerts[0]
	if f.Fingerprint != r.Fingerprint {
		t.Fatalf("fingerprints differ: %s vs %s", f.Fingerprint, r.Fingerprint)
	}
	if len(f.Fingerprint) != 16 {
		t.Fatalf("fingerprint %q is not 16 hex chars", f.Fingerprint)
	}
}

func TestFiringAlertHasZeroEndsAt(t *testing.T) {
	body, _ := json.Marshal(build(t, "firing"))
	if !strings.Contains(string(body), `"endsAt":"0001-01-01T00:00:00Z"`) {
		t.Fatalf("firing alert must have zero endsAt: %s", body)
	}
}

func TestMixedMatchesGrafanaTitle(t *testing.T) {
	m := build(t, "mixed")
	if m.Status != "firing" || m.State != "alerting" {
		t.Fatalf("status=%s state=%s", m.Status, m.State)
	}
	if want := "[FIRING:1, RESOLVED:1] HighErrorRate prod (critical)"; m.Title != want {
		t.Fatalf("title %q, want %q", m.Title, want)
	}
	if want := `{}/{__grafana_autogenerated__="true"}/{__grafana_receiver__="larek-webhook"}:{alertname="HighErrorRate", grafana_folder="prod"}`; m.GroupKey != want {
		t.Fatalf("groupKey %q", m.GroupKey)
	}
}

func TestResolvedGroup(t *testing.T) {
	m := build(t, "resolved")
	if m.Status != "resolved" || m.State != "ok" {
		t.Fatalf("status=%s state=%s", m.Status, m.State)
	}
	if !strings.HasPrefix(m.Title, "[RESOLVED] HighErrorRate prod") {
		t.Fatalf("title %q", m.Title)
	}
	if m.Alerts[0].EndsAt.IsZero() {
		t.Fatal("resolved alert must have endsAt")
	}
}

func TestEmptyValuesAreNull(t *testing.T) {
	for _, name := range []string{"empty_values", "no_data"} {
		body, _ := json.Marshal(build(t, name))
		if !strings.Contains(string(body), `"values":null`) {
			t.Fatalf("%s: values must be null: %s", name, body)
		}
	}
}

func TestAllScenariosBuild(t *testing.T) {
	for _, s := range scenarios {
		m := build(t, s.Name)
		if len(m.Alerts) == 0 {
			t.Errorf("%s: no alerts", s.Name)
		}
		if m.CommonAnnotations == nil || m.GroupLabels == nil {
			t.Errorf("%s: maps must be objects, not null", s.Name)
		}
		if _, err := json.Marshal(m); err != nil {
			t.Errorf("%s: %v", s.Name, err)
		}
	}
}

func TestSenderRetriesOn5xx(t *testing.T) {
	var calls atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if u, p, ok := r.BasicAuth(); !ok || u != "grafana" || p != "secret" {
			t.Errorf("basic auth not sent")
		}
		if calls.Add(1) < 3 {
			w.WriteHeader(http.StatusServiceUnavailable)
			return
		}
		w.Write([]byte("ok"))
	}))
	defer srv.Close()

	s := &Sender{Client: srv.Client(), Auth: Auth{User: "grafana", Password: "secret"}, Retries: 2, Backoff: time.Millisecond}
	res := s.Send(context.Background(), srv.URL, []byte(`{}`))
	if !res.OK() || res.Attempts != 3 || res.Response != "ok" {
		t.Fatalf("got %+v", res)
	}
}

func TestSenderDoesNotRetry4xx(t *testing.T) {
	var calls atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		calls.Add(1)
		if r.Header.Get("Authorization") != "Bearer t0ken" {
			t.Errorf("authorization header not sent")
		}
		w.WriteHeader(http.StatusBadRequest)
	}))
	defer srv.Close()

	s := &Sender{Client: srv.Client(), Auth: Auth{Header: "Bearer t0ken"}, Retries: 2, Backoff: time.Millisecond}
	res := s.Send(context.Background(), srv.URL, []byte(`{}`))
	if res.OK() || res.Attempts != 1 || calls.Load() != 1 {
		t.Fatalf("got %+v, calls %d", res, calls.Load())
	}
}
